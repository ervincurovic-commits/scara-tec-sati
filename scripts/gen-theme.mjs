// Generates src/theme.css: the Tailwind palette as CSS variables for the
// dark (original) theme and a remapped set for the light theme.
// Run: node scripts/gen-theme.mjs
import colors from 'tailwindcss/colors.js';
import { writeFileSync } from 'node:fs';

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const ACCENTS = ['indigo', 'emerald', 'amber', 'red'];

const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

// Light theme: which original shade each class shade should render as.
// Neutrals flip so dark surfaces become light ones; cards (800) turn white.
const LIGHT_SLATE = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 500, 500: 400, 600: 300, 700: 200, 800: 'white', 900: 100, 950: 200 };
// Accents flip the tints used for badges and text, but keep the solid
// button shades (500, 600) so buttons look the same in both themes.
const LIGHT_ACCENT = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 600, 700: 300, 800: 200, 900: 100, 950: 50 };

const lines = [];
lines.push('/* Generated by scripts/gen-theme.mjs. Do not edit by hand. */');
lines.push(':root {');
lines.push('  --white: 255 255 255;');
lines.push('  --black: 0 0 0;');
for (const name of ['slate', ...ACCENTS]) {
  for (const s of SHADES) lines.push(`  --${name}-${s}: ${rgb(colors[name][s])};`);
}
lines.push('}');
lines.push('');
lines.push(':root[data-theme="light"] {');
lines.push(`  --white: ${rgb(colors.slate[900])};`);
for (const s of SHADES) {
  const to = LIGHT_SLATE[s];
  lines.push(`  --slate-${s}: ${to === 'white' ? '255 255 255' : rgb(colors.slate[to])};`);
}
for (const name of ACCENTS) {
  for (const s of SHADES) lines.push(`  --${name}-${s}: ${rgb(colors[name][LIGHT_ACCENT[s]])};`);
}
lines.push('}');
lines.push('');
writeFileSync(new URL('../src/theme.css', import.meta.url), lines.join('\n'));
console.log('src/theme.css written');
