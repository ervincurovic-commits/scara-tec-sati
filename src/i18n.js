const DICTS = { bs, sl };
const STORAGE_KEY = 'scara_lang';

let lang = 'bs';

export function getLang() {
  return lang;
}

/** Translates a key; `{name}` placeholders are filled from params. */
export function t(key, params) {
  const text = DICTS[lang][key] ?? bs[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/** Fills every element that declares its text through data-i18n attributes. */
export function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-action="set-lang"]').forEach((el) => {
    el.classList.toggle('is-active', el.dataset.lang === lang);
  });
  document.documentElement.lang = lang;
  document.title = t('app.title');
}

export function setLang(next) {
  lang = next === 'sl' ? 'sl' : 'bs';
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* private mode: the choice just does not persist */
  }
  applyStaticI18n();
}

export function initI18n() {
  try {
    lang = localStorage.getItem(STORAGE_KEY) === 'sl' ? 'sl' : 'bs';
  } catch {
    lang = 'bs';
  }
  applyStaticI18n();
}

